import {readFile, writeFile, mkdir} from 'node:fs/promises';
import {execFileSync} from 'node:child_process';
import {dirname, join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {build} from 'esbuild';
import {propSchema, resolveParams, shotDurationFrames} from './src/showcase/params.mjs';

const root=dirname(fileURLToPath(import.meta.url));
const componentId='device-ui-motion', mediaId='recipe-media-device-ui-model';
const workspace=JSON.parse(await readFile(join(root,'cueframe.json'),'utf8'));
const manifest=workspace.components[componentId].manifest;
const bundled=await build({
  absWorkingDir:root, entryPoints:['src/Showcase.jsx'], bundle:true, write:false,
  format:'esm', platform:'browser', target:'chrome144', jsx:'preserve',
  // Bundle owned modules only. CueFrame's CLI admits runtime imports; this
  // package neither copies its allowlist nor installs the rendering runtime.
  packages:'external',
});
const tsxSource=bundled.outputFiles[0].text;
const source={version:2,componentId,tsxSource,manifest};
const fps=60, duration=shotDurationFrames(resolveParams(),fps)/fps;
const template={v:1,format:{aspectRatio:'16:9',fps,resolution:'hd'},tracks:[{
  id:'device-ui',kind:'overlay',name:'Device UI showcase',contents:[{
    id:'device-ui-showcase',kind:'overlay',startTime:0,duration,
    source:{kind:'component',componentId,props:{shot:'film'},assets:{model:'REPLACE_WITH_MEDIA_ID'},zPlane:'front'},
  }],
}]};
const composition=structuredClone(template);
const clip=composition.tracks[0].contents[0];
clip.source.assets.model=mediaId;
const cloudBrandKit={kitId:'cueframe-recipes-device-ui-motion',name:'Device UI Motion',
  description:'Unbranded glass UI showcase.',colors:{primary:'#aeb2ba',secondary:'#8d8d92',accent:'#f5f5f5',background:'#000000',text:'#f5f5f5'},
  headingFont:{fontFamily:'Inter',fontWeight:600},bodyFont:{fontFamily:'Inter',fontWeight:500}};
const project={version:4,id:'recipe-device-ui-motion',name:'Device UI Motion',createdAt:0,modifiedAt:0,composition,
  pool:[{id:mediaId,name:'Baked device mesh.svg',kind:'image',filePath:null,cloud:null}],
  recipe:{schemaVersion:1,slug:'device-ui-motion',mediaSlots:[{id:'model',projectMediaId:mediaId,label:'Baked device mesh SVG',kind:'image'}],
    components:[{componentId,name:'Device UI Motion',category:'layouts',propSchema}],cloudBrandKit},
};
const componentDir=join(root,'cueframe/components',componentId);
const json=value=>JSON.stringify(value,null,2)+'\n';
// The established recipe loader fetches index.tsx and config.ts only. Keep both
// self-contained; modular authoring files are not runtime dependencies.
const configSource=`// GENERATED by build-project-template.mjs; edit src/showcase/schema.json instead.\nimport {z} from 'zod';\nimport component from './index';\nconst schema=${JSON.stringify(propSchema)};\nexport const config={id:'device-ui-motion',name:'Device UI Motion',kind:'component',category:'layouts',version:'1.0.0',component,paramsSchema:z.fromJSONSchema(schema)};\nexport default config;\n`;
const outputs=[
  [join(componentDir,'index.tsx'),tsxSource], [join(componentDir,'config.ts'),configSource],
  [join(componentDir,'schema.json'),json(propSchema)], [join(root,'composition.template.json'),json(template)],
  [join(root,'brand-kit.json'),json(cloudBrandKit)],
];
const check=process.argv.includes('--check');
// The public CLI owns admission, canonical hashes and project packaging. For
// unreleased CLI development CUEFRAME_CLI may name the built JS executable.
const cli=process.env.CUEFRAME_CLI || 'cueframe';
const isScript=/\.[cm]?js$/.test(cli);
const args=[...(isScript ? [cli] : []),'recipe','pack','--body','@-',
  '--out',join(root,'recipe.cueframe'),'--json',...(check ? ['--check'] : [])];
try {
  const result=execFileSync(isScript ? process.execPath : cli,args,{
    input:json({version:1,project,components:[source]}),encoding:'utf8',stdio:['pipe','pipe','pipe'],
  });
  process.stdout.write(result);
} catch(error) {
  if(error.code==='ENOENT') {
    throw Error('CueFrame CLI not found. Install a CLI with "recipe pack", or set CUEFRAME_CLI to its executable.',{cause:error});
  }
  throw Error(`CueFrame recipe pack failed:\n${error.stdout || ''}${error.stderr || error.message}`,{cause:error});
}
if(check) {
  for(const [path,expected] of outputs) if(await readFile(path,'utf8')!==expected) throw Error(`Stale generated file: ${path}`);
} else {
  await mkdir(componentDir,{recursive:true});
  await Promise.all(outputs.map(([path,content])=>writeFile(path,content)));
}
console.log(`Built ${componentId}: ${Buffer.byteLength(tsxSource)} source bytes, ${duration}s`);
